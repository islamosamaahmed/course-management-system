BEGIN;

CREATE TABLE exam_certificates (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  attempt_id INTEGER NOT NULL UNIQUE REFERENCES exam_attempts(id) ON DELETE CASCADE,
  student_id INTEGER NOT NULL REFERENCES students(id) ON DELETE CASCADE,
  exam_id INTEGER NOT NULL REFERENCES exams(id) ON DELETE CASCADE,
  certificate_number TEXT NOT NULL UNIQUE,
  student_name TEXT NOT NULL,
  exam_title TEXT NOT NULL,
  subject_name TEXT NOT NULL,
  lecture_title TEXT NOT NULL,
  score INTEGER NOT NULL CHECK(score >= 0),
  percentage REAL NOT NULL CHECK(percentage BETWEEN 0 AND 100),
  total_questions INTEGER NOT NULL CHECK(total_questions > 0),
  issuer_name TEXT NOT NULL,
  issued_at TEXT NOT NULL,
  issued_by INTEGER REFERENCES users(id) ON DELETE SET NULL
);

CREATE INDEX exam_certificates_student_issued
  ON exam_certificates(student_id, issued_at DESC);

COMMIT;
