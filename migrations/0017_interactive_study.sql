CREATE TABLE study_units (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  subject_id INTEGER NOT NULL REFERENCES subjects(id) ON DELETE RESTRICT,
  level_id INTEGER NOT NULL REFERENCES levels(id) ON DELETE RESTRICT,
  title TEXT NOT NULL CHECK(length(trim(title)) BETWEEN 2 AND 160),
  sort_order INTEGER NOT NULL DEFAULT 0,
  created_by INTEGER REFERENCES users(id) ON DELETE SET NULL,
  created_at TEXT NOT NULL DEFAULT (to_char(clock_timestamp() AT TIME ZONE 'UTC', 'YYYY-MM-DD"T"HH24:MI:SS.MS"Z"')),
  updated_at TEXT NOT NULL DEFAULT (to_char(clock_timestamp() AT TIME ZONE 'UTC', 'YYYY-MM-DD"T"HH24:MI:SS.MS"Z"')),
  UNIQUE(subject_id,title),
  UNIQUE(id,subject_id,level_id)
);

CREATE TABLE study_lessons (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  subject_id INTEGER NOT NULL REFERENCES subjects(id) ON DELETE CASCADE,
  unit_id INTEGER NOT NULL REFERENCES study_units(id) ON DELETE CASCADE,
  level_id INTEGER NOT NULL REFERENCES levels(id) ON DELETE RESTRICT,
  group_id INTEGER NOT NULL REFERENCES groups_table(id) ON DELETE RESTRICT,
  title TEXT NOT NULL CHECK(length(trim(title)) BETWEEN 2 AND 160),
  description TEXT NOT NULL DEFAULT '',
  status TEXT NOT NULL DEFAULT 'draft' CHECK(status IN ('draft','published')),
  created_by INTEGER REFERENCES users(id) ON DELETE SET NULL,
  created_at TEXT NOT NULL DEFAULT (to_char(clock_timestamp() AT TIME ZONE 'UTC', 'YYYY-MM-DD"T"HH24:MI:SS.MS"Z"')),
  updated_at TEXT NOT NULL DEFAULT (to_char(clock_timestamp() AT TIME ZONE 'UTC', 'YYYY-MM-DD"T"HH24:MI:SS.MS"Z"')),
  UNIQUE(id,subject_id,level_id,group_id),
  FOREIGN KEY(unit_id,subject_id,level_id) REFERENCES study_units(id,subject_id,level_id) ON DELETE CASCADE
);

CREATE TABLE study_sections (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  lesson_id INTEGER NOT NULL REFERENCES study_lessons(id) ON DELETE CASCADE,
  title TEXT NOT NULL CHECK(length(trim(title)) BETWEEN 2 AND 160),
  content TEXT NOT NULL CHECK(length(trim(content)) BETWEEN 2 AND 12000),
  image_material_id INTEGER REFERENCES course_materials(id) ON DELETE SET NULL,
  sort_order INTEGER NOT NULL DEFAULT 0,
  created_at TEXT NOT NULL DEFAULT (to_char(clock_timestamp() AT TIME ZONE 'UTC', 'YYYY-MM-DD"T"HH24:MI:SS.MS"Z"')),
  UNIQUE(id,lesson_id)
);

CREATE TABLE study_questions (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  section_id INTEGER NOT NULL REFERENCES study_sections(id) ON DELETE CASCADE,
  question_text TEXT NOT NULL CHECK(length(trim(question_text)) BETWEEN 2 AND 2000),
  question_type TEXT NOT NULL CHECK(question_type IN ('multiple_choice','true_false')),
  options_json TEXT NOT NULL DEFAULT '[]',
  correct_answer TEXT NOT NULL,
  explanation TEXT NOT NULL CHECK(length(trim(explanation)) BETWEEN 2 AND 3000),
  sort_order INTEGER NOT NULL DEFAULT 0,
  created_at TEXT NOT NULL DEFAULT (to_char(clock_timestamp() AT TIME ZONE 'UTC', 'YYYY-MM-DD"T"HH24:MI:SS.MS"Z"')),
  UNIQUE(id,section_id)
);

CREATE TABLE study_lesson_progress (
  student_id INTEGER NOT NULL REFERENCES students(id) ON DELETE CASCADE,
  lesson_id INTEGER NOT NULL REFERENCES study_lessons(id) ON DELETE CASCADE,
  last_section_id INTEGER REFERENCES study_sections(id) ON DELETE SET NULL,
  completed_at TEXT,
  created_at TEXT NOT NULL DEFAULT (to_char(clock_timestamp() AT TIME ZONE 'UTC', 'YYYY-MM-DD"T"HH24:MI:SS.MS"Z"')),
  updated_at TEXT NOT NULL DEFAULT (to_char(clock_timestamp() AT TIME ZONE 'UTC', 'YYYY-MM-DD"T"HH24:MI:SS.MS"Z"')),
  PRIMARY KEY(student_id,lesson_id)
);

CREATE TABLE study_question_attempts (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  student_id INTEGER NOT NULL REFERENCES students(id) ON DELETE CASCADE,
  question_id INTEGER NOT NULL REFERENCES study_questions(id) ON DELETE CASCADE,
  selected_answer TEXT NOT NULL,
  is_correct BOOLEAN NOT NULL,
  answered_at TEXT NOT NULL DEFAULT (to_char(clock_timestamp() AT TIME ZONE 'UTC', 'YYYY-MM-DD"T"HH24:MI:SS.MS"Z"'))
);

CREATE INDEX study_units_subject_order ON study_units(subject_id,sort_order,id);
CREATE INDEX study_lessons_student_available ON study_lessons(level_id,group_id,status,subject_id,unit_id);
CREATE INDEX study_sections_lesson_order ON study_sections(lesson_id,sort_order,id);
CREATE INDEX study_questions_section_order ON study_questions(section_id,sort_order,id);
CREATE INDEX study_lesson_progress_student ON study_lesson_progress(student_id,updated_at DESC);
CREATE INDEX study_question_attempts_student_question ON study_question_attempts(student_id,question_id,answered_at DESC,id DESC);

