import dotenv from 'dotenv';
import { DatabaseSync } from 'node:sqlite';
import pg from 'pg';
import { readFile } from 'node:fs/promises';
import { resolve } from 'node:path';

dotenv.config({ path: resolve(process.cwd(), '.env.local') });
const { Pool } = pg;

const sourcePath = resolve(process.argv[2] || 'data/course.sqlite');
const tableOrder = [
  'courses', 'levels', 'users', 'groups_table', 'course_settings', 'level_course_prices',
  'students', 'enrollments', 'subjects', 'course_sessions', 'attendance', 'payments',
  'auth_sessions', 'audit_logs', 'schema_migrations', 'notifications', 'course_lectures',
  'exams', 'exam_questions', 'exam_attempts', 'exam_attempt_questions', 'exam_answers',
  'exam_integrity_events', 'certificates', 'exam_certificates', 'course_materials', 'system_wipe_requests'
];
const identityTables = new Set([
  'courses', 'levels', 'groups_table', 'users', 'students', 'enrollments',
  'course_sessions', 'attendance', 'payments', 'audit_logs', 'notifications',
  'course_settings', 'subjects', 'course_lectures', 'exams', 'exam_questions',
  'exam_attempts', 'exam_attempt_questions', 'exam_answers', 'exam_integrity_events',
  'certificates', 'exam_certificates', 'course_materials'
]);
const quoteIdentifier = identifier => `"${identifier.replaceAll('"', '""')}"`;
const toPostgres = statement => statement
  .replace(/\b(id\s+)INTEGER\s+PRIMARY\s+KEY\b/gi, '$1INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY')
  .replace(/\bexpires_at\s+INTEGER\b/gi, 'expires_at BIGINT')
  .replace(/role\s+TEXT\s+NOT NULL\s+CHECK\s*\(\s*role\s+IN\s*\('admin','assistant','student'\)\s*\)/i,
    "role TEXT NOT NULL CHECK(role IN ('admin','doctor','assistant','student'))")
  .replace(/\s+COLLATE\s+NOCASE\b/gi, '')
  .replace(/strftime\('%Y-%m-%dT%H:%M:%fZ','now'\)/g,
    `to_char(clock_timestamp() AT TIME ZONE 'UTC', 'YYYY-MM-DD"T"HH24:MI:SS.MS"Z"')`);

if (!process.env.DATABASE_URL_LOCAL && !process.env.DATABASE_URL_UNPOOLED && !process.env.DATABASE_URL) {
  throw new Error('Set DATABASE_URL_LOCAL, DATABASE_URL_UNPOOLED, or DATABASE_URL in .env.local before migrating.');
}

const source = new DatabaseSync(sourcePath, { readOnly: true });
const pool = new Pool({
  connectionString: process.env.DATABASE_URL_LOCAL || process.env.DATABASE_URL_UNPOOLED || process.env.DATABASE_URL
});

try {
  const tableDefinitions = source.prepare(`
    SELECT name, sql FROM sqlite_master
    WHERE type='table' AND name NOT LIKE 'sqlite_%'
  `).all();
  const definitions = new Map(tableDefinitions.map(item => [item.name, item.sql]));
  const optionalTables = new Set(['certificates', 'exam_certificates', 'course_materials', 'system_wipe_requests']);
  const missing = tableOrder.filter(name => !definitions.has(name) && !optionalTables.has(name));
  if (missing.length) throw new Error(`The local SQLite database is missing tables: ${missing.join(', ')}`);

  const existingMigration = await pool.query(
    "SELECT to_regclass('public.neon_data_migrations') AS table_name"
  );
  const schemaVersions = new Set((await pool.query('SELECT version FROM schema_migrations')).rows.map(row => Number(row.version)));
  const requiredVersions = [7, 8, 9, 10, 11, 12, 13, 14];
  const pendingVersions = requiredVersions.filter(version => !schemaVersions.has(version));
  if (existingMigration.rows[0].table_name) {
    const migrated = await pool.query(
      "SELECT 1 FROM neon_data_migrations WHERE name='course-sqlite-v1'"
    );
    if (migrated.rowCount && !pendingVersions.length) {
      console.log('Migration already completed; no rows were changed.');
      process.exitCode = 0;
    } else if (!migrated.rowCount) {
      throw new Error('A previous migration schema exists without a completion record; refusing to overwrite Neon data.');
    }
  }
  if (existingMigration.rows[0].table_name && pendingVersions.length) {
    const client = await pool.connect();
    try {
      await client.query('BEGIN');
      for (const version of pendingVersions) {
        if (schemaVersions.has(version)) continue;
        const migration = await readFile(resolve(process.cwd(), 'migrations', `${String(version).padStart(4, '0')}_${({
          7: 'student_certificates',
          8: 'course_materials',
          9: 'system_wipe_requests',
          10: 'doctor_role',
          11: 'restore_known_staff_names',
          12: 'exam_certificates',
          13: 'ai_chat',
          14: 'ai_pending_actions'
        })[version]}.sql`), 'utf8');
        const statements = toPostgres(migration)
          .replace(/^\s*BEGIN\s*;\s*/i, '')
          .replace(/\s*COMMIT\s*;\s*$/i, '');
        await client.query(statements);
        await client.query('INSERT INTO schema_migrations(version) VALUES($1) ON CONFLICT(version) DO NOTHING', [version]);
        schemaVersions.add(version);
      }
      await client.query('COMMIT');
      console.log(`Applied ${pendingVersions.length} pending migration(s): ${pendingVersions.join(', ')}`);
    } catch (error) {
      await client.query('ROLLBACK');
      throw error;
    } finally {
      client.release();
    }
  } else if (!existingMigration.rows[0].table_name) {
    const client = await pool.connect();
    try {
      await client.query('BEGIN');
      for (const name of tableOrder) {
        if (definitions.has(name)) await client.query(toPostgres(definitions.get(name)));
      }
      for (const { sql } of source.prepare(`
        SELECT sql FROM sqlite_master
        WHERE type='index' AND sql IS NOT NULL ORDER BY name
      `).all()) {
        await client.query(toPostgres(sql));
      }
      await client.query('CREATE UNIQUE INDEX users_username_lower_idx ON users (LOWER(username))');
      await client.query(`CREATE TABLE neon_data_migrations (
        name TEXT PRIMARY KEY,
        completed_at TEXT NOT NULL
      )`);

      const targetTables = await client.query(`
        SELECT tablename FROM pg_tables WHERE schemaname='public'
      `);
      const targetNames = new Set(targetTables.rows.map(row => row.tablename));
      const occupied = [];
      for (const table of tableOrder) {
        if (!targetNames.has(table)) continue;
        const { rows } = await client.query(`SELECT COUNT(*)::int AS count FROM ${quoteIdentifier(table)}`);
        if (rows[0].count) occupied.push(table);
      }
      if (occupied.length) {
        throw new Error(`Neon already contains data in ${occupied.join(', ')}; refusing to replace it.`);
      }

      const counts = {};
      for (const table of tableOrder) {
        if (!definitions.has(table)) {
          counts[table] = 0;
          continue;
        }
        const columns = source.prepare(`PRAGMA table_info(${quoteIdentifier(table)})`).all().map(column => column.name);
        const rows = table === 'auth_sessions' && process.env.DATABASE_URL_LOCAL
          ? []
          : source.prepare(`SELECT * FROM ${quoteIdentifier(table)}`).all();
        counts[table] = rows.length;
        if (!rows.length) continue;
        const columnList = columns.map(quoteIdentifier).join(', ');
        const values = `(${columns.map((_, index) => `$${index + 1}`).join(', ')})`;
        const insert = `INSERT INTO ${quoteIdentifier(table)} (${columnList}) VALUES ${values}`;
        for (const row of rows) {
          await client.query(insert, columns.map(column => row[column]));
        }
      }

      const targetVersions = new Set((await client.query('SELECT version FROM schema_migrations')).rows.map(row => row.version));
      for (const version of [7, 8, 9, 10, 11, 12, 13, 14]) {
        if (targetVersions.has(version)) continue;
        const migration = await readFile(resolve(process.cwd(), 'migrations', `${String(version).padStart(4, '0')}_${({
          7: 'student_certificates',
          8: 'course_materials',
          9: 'system_wipe_requests',
          10: 'doctor_role',
          11: 'restore_known_staff_names',
          12: 'exam_certificates',
          13: 'ai_chat',
          14: 'ai_pending_actions'
        })[version]}.sql`), 'utf8');
        const statements = toPostgres(migration)
          .replace(/^\s*BEGIN\s*;\s*/i, '')
          .replace(/\s*COMMIT\s*;\s*$/i, '');
        await client.query(statements);
        await client.query('INSERT INTO schema_migrations(version) VALUES($1) ON CONFLICT(version) DO NOTHING', [version]);
        targetVersions.add(version);
      }
      for (const table of tableOrder) {
        if (identityTables.has(table) && counts[table]) {
          await client.query(
            `SELECT setval(pg_get_serial_sequence($1, 'id'), (SELECT MAX(id) FROM ${quoteIdentifier(table)}))`,
            [`public.${table}`]
          );
        }
      }
      await client.query(
        `INSERT INTO neon_data_migrations(name,completed_at)
         VALUES('course-sqlite-v1',to_char(clock_timestamp() AT TIME ZONE 'UTC', 'YYYY-MM-DD"T"HH24:MI:SS.MS"Z"'))`
      );
      await client.query('COMMIT');
      console.log(`Migrated ${Object.values(counts).reduce((sum, count) => sum + count, 0)} records from ${sourcePath}.`);
      for (const [table, count] of Object.entries(counts)) console.log(`${table}: ${count}`);
    } catch (error) {
      await client.query('ROLLBACK');
      throw error;
    } finally {
      client.release();
    }
  }
} finally {
  source.close();
  await pool.end();
}
