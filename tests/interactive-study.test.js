async function createStudyServer() {
  const pg = new PGlite();
  await pg.exec(`
    CREATE TABLE users(id INTEGER PRIMARY KEY, name TEXT NOT NULL);
    CREATE TABLE levels(id INTEGER PRIMARY KEY, name TEXT NOT NULL);
    CREATE TABLE groups_table(id INTEGER PRIMARY KEY, level_id INTEGER NOT NULL REFERENCES levels(id), name TEXT NOT NULL);
    CREATE TABLE subjects(id INTEGER PRIMARY KEY, doctor_id INTEGER NOT NULL REFERENCES users(id),
      level_id INTEGER NOT NULL REFERENCES levels(id), name TEXT NOT NULL);
    CREATE TABLE students(id INTEGER PRIMARY KEY, user_id INTEGER NOT NULL REFERENCES users(id),
      level_id INTEGER NOT NULL REFERENCES levels(id), group_id INTEGER NOT NULL REFERENCES groups_table(id),
      active INTEGER NOT NULL, cancelled_at TEXT);
    CREATE TABLE enrollments(student_id INTEGER NOT NULL REFERENCES students(id),group_id INTEGER NOT NULL REFERENCES groups_table(id),
      starts_on TEXT NOT NULL,ends_on TEXT);
    CREATE TABLE course_materials(id INTEGER PRIMARY KEY,subject_id INTEGER NOT NULL REFERENCES subjects(id),
      level_id INTEGER NOT NULL REFERENCES levels(id),file_name TEXT NOT NULL,title TEXT NOT NULL,content_type TEXT NOT NULL);
    CREATE TABLE permission_catalog(permission_key TEXT PRIMARY KEY,category TEXT NOT NULL,description TEXT NOT NULL);
    CREATE TABLE audit_logs(id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,actor_id INTEGER,actor_name TEXT,
      action TEXT,entity TEXT,entity_id INTEGER,details TEXT);
    INSERT INTO users(id,name) VALUES(1,'Admin'),(10,'Doctor A'),(11,'Doctor B'),(20,'Student A'),(21,'Student B'),(30,'Assistant');
    INSERT INTO levels(id,name) VALUES(1,'Year 1'),(2,'Year 2');
    INSERT INTO groups_table(id,level_id,name) VALUES(101,1,'Group A'),(102,1,'Group B'),(201,2,'Group C');
    INSERT INTO subjects(id,doctor_id,level_id,name) VALUES(1,10,1,'Accounting'),(2,11,1,'Physics');
    INSERT INTO students(id,user_id,level_id,group_id,active) VALUES(201,20,1,101,1),(202,21,1,102,1);
    INSERT INTO enrollments(student_id,group_id,starts_on) VALUES(201,101,'2020-01-01'),(202,102,'2020-01-01');
  `);
  const migration = await readFile(new URL('../migrations/0017_interactive_study.sql', import.meta.url), 'utf8');
  await pg.exec(migration);

  const query = async (statement, parameters = []) => {
    let index = 0;
    let sql = statement.replace(/\?/g, () => `$${++index}`);
    if (/^\s*INSERT INTO (study_units|study_lessons|study_sections|study_questions|study_question_attempts)\b/i.test(sql) &&
        !/\bRETURNING\b/i.test(sql) && !/\bON CONFLICT\b/i.test(sql)) sql += ' RETURNING id';
    const result = await pg.query(sql, parameters);
    return { ...result, changes: result.rowCount, lastInsertRowid: result.rows?.[0]?.id };
  };
  const db = {
    query,
    pool: {
      async connect() {
        return { query, release() {} };
      }
    },
    async close() { await pg.close(); }
  };
  const app = express();
  app.use(express.json());
  app.use((req, _res, next) => {
    const role = req.get('x-role') || 'student';
    const id = { admin: 1, doctor: 10, 'other-doctor': 11, student: 20, 'other-student': 21, assistant: 30 }[role];
    req.user = { id, role: role === 'other-doctor' ? 'doctor' : role === 'other-student' ? 'student' : role, name: role };
    next();
  });
  registerInteractiveStudyRoutes(app, db);
  app.use((error, _req, res, _next) => res.status(error.status || 500).json({ error: error.message }));
  const server = app.listen(0, '127.0.0.1');
  await new Promise((resolve, reject) => {
    server.once('listening', resolve);
    server.once('error', reject);
  });
  return { server, db, base: `http://127.0.0.1:${server.address().port}` };
}

async function request(base, path, { role = 'student', method = 'GET', body } = {}) {
  const response = await fetch(`${base}/api${path}`, {
    method,
    headers: { 'Content-Type': 'application/json', 'x-role': role },
    ...(body === undefined ? {} : { body: JSON.stringify(body) })
  });
  const result = await response.json();
  return { response, result };
}

test('Interactive Study authoring, access rules, answer feedback, saved progress, and mistake review', async () => {
  const { server, db, base } = await createStudyServer();
  try {
    const teacherContents = await request(base, '/interactive-study/manage', { role: 'doctor' });
    assert.equal(teacherContents.response.status, 200);
    assert.deepEqual(teacherContents.result.subjects.map(subject => subject.id), [1]);
    const foreignSubjectUnit = await request(base, '/interactive-study/manage/units', {
      role: 'doctor', method: 'POST', body: { subject_id: 2, title: 'Private unit' }
    });
    assert.equal(foreignSubjectUnit.response.status, 403);

    const unitResult = await request(base, '/interactive-study/manage/units', {
      role: 'doctor', method: 'POST', body: { subject_id: 1, title: 'Chapter 1' }
    });
    assert.equal(unitResult.response.status, 201, JSON.stringify(unitResult.result));
    const unitId = unitResult.result.id;
    const lessonResult = await request(base, '/interactive-study/manage/lessons', {
      role: 'doctor', method: 'POST', body: {
        title: 'Accounting basics', description: 'Learn the foundations',
        subject_id: 1, unit_id: unitId, level_id: 1, group_id: 101, status: 'draft'
      }
    });
    assert.equal(lessonResult.response.status, 201, JSON.stringify(lessonResult.result));
    const lessonId = lessonResult.result.id;
    const prematurePublish = await request(base, `/interactive-study/manage/lessons/${lessonId}`, {
      role: 'doctor', method: 'PATCH', body: { status: 'published' }
    });
    assert.equal(prematurePublish.response.status, 409);

    const section1 = await request(base, `/interactive-study/manage/lessons/${lessonId}/sections`, {
      role: 'doctor', method: 'POST', body: {
        title: 'ما هي المحاسبة؟', content: 'المحاسبة نظام لتسجيل العمليات المالية وتصنيفها وتلخيصها.'
      }
    });
    const section2 = await request(base, `/interactive-study/manage/lessons/${lessonId}/sections`, {
      role: 'doctor', method: 'POST', body: {
        title: 'أهمية المعلومات المالية', content: 'تساعد المعلومات المالية على فهم أداء المنشأة.'
      }
    });
    assert.equal(section1.response.status, 201, JSON.stringify(section1.result));
    assert.equal(section2.response.status, 201, JSON.stringify(section2.result));
    const firstQuestion = await request(base, `/interactive-study/manage/sections/${section1.result.id}/questions`, {
      role: 'doctor', method: 'POST', body: {
        question_text: 'ما الهدف الأساسي من المحاسبة؟', question_type: 'multiple_choice',
        options: ['تسجيل العمليات المالية', 'زيادة المبيعات', 'إدارة الموظفين', 'تحديد الأسعار'],
        correct_answer: 'تسجيل العمليات المالية', explanation: 'المحاسبة تسجل العمليات المالية وتنظم بياناتها.'
      }
    });
    const secondQuestion = await request(base, `/interactive-study/manage/sections/${section1.result.id}/questions`, {
      role: 'doctor', method: 'POST', body: {
        question_text: 'تساعد المحاسبة على تنظيم المعاملات.', question_type: 'true_false',
        correct_answer: 'true', explanation: 'تُستخدم المحاسبة لتسجيل المعاملات وتصنيفها.'
      }
    });
    const thirdQuestion = await request(base, `/interactive-study/manage/sections/${section2.result.id}/questions`, {
      role: 'doctor', method: 'POST', body: {
        question_text: 'المعلومات المالية لا تساعد في اتخاذ القرار.', question_type: 'true_false',
        correct_answer: 'false', explanation: 'تساعد المعلومات المالية في اتخاذ قرارات أفضل.'
      }
    });
    for (const result of [firstQuestion, secondQuestion, thirdQuestion]) assert.equal(result.response.status, 201, JSON.stringify(result.result));
    const publish = await request(base, `/interactive-study/manage/lessons/${lessonId}`, {
      role: 'doctor', method: 'PATCH', body: { status: 'published' }
    });
    assert.equal(publish.response.status, 200, JSON.stringify(publish.result));

    const studentCatalog = await request(base, '/student/study');
    assert.equal(studentCatalog.response.status, 200, JSON.stringify(studentCatalog.result));
    assert.equal(studentCatalog.result.subjects[0].name, 'Accounting');
    assert.equal(studentCatalog.result.subjects[0].units[0].lessons[0].id, lessonId);
    const otherGroup = await request(base, `/student/study/lessons/${lessonId}`, { role: 'other-student' });
    assert.equal(otherGroup.response.status, 404);
    const unprivilegedCreate = await request(base, '/interactive-study/manage/units', {
      role: 'assistant', method: 'POST', body: { subject_id: 1, title: 'No access' }
    });
    assert.equal(unprivilegedCreate.response.status, 403);
    const studentEdit = await request(base, `/interactive-study/manage/lessons/${lessonId}`, {
      method: 'PATCH', body: { status: 'draft' }
    });
    assert.equal(studentEdit.response.status, 403);

    const lesson = await request(base, `/student/study/lessons/${lessonId}`);
    assert.equal(lesson.response.status, 200);
    const q1 = lesson.result.sections[0].questions[0];
    assert.equal(Object.hasOwn(q1, 'correct_answer'), false);
    assert.equal(Object.hasOwn(q1, 'explanation'), false);
    const wrong = await request(base, `/student/study/questions/${firstQuestion.result.id}/answer`, {
      method: 'POST', body: { answer: 'زيادة المبيعات' }
    });
    assert.equal(wrong.response.status, 200);
    assert.equal(wrong.result.correct, false);
    assert.equal(wrong.result.correct_answer, 'تسجيل العمليات المالية');
    assert.match(wrong.result.explanation, /تسجل العمليات المالية/);

    const resumed = await request(base, `/student/study/lessons/${lessonId}`);
    assert.equal(resumed.result.sections[0].questions[0].answered, true);
    assert.equal(resumed.result.sections[0].questions[0].correct_answer, 'تسجيل العمليات المالية');
    assert.equal(resumed.result.sections[0].questions[1].answered, false);
    assert.equal(resumed.result.progress.completed_sections, 0);
    const firstReview = await request(base, '/student/study/review');
    assert.equal(firstReview.result.items.length, 1);
    assert.equal(Object.hasOwn(firstReview.result.items[0], 'explanation'), false);

    const secondAnswer = await request(base, `/student/study/questions/${secondQuestion.result.id}/answer`, {
      method: 'POST', body: { answer: 'true' }
    });
    assert.equal(secondAnswer.result.correct, true);
    const progress = await request(base, `/student/study/lessons/${lessonId}`);
    assert.equal(progress.result.progress.completed_sections, 1);
    assert.equal(progress.result.progress.completion_percentage, 50);

    const thirdAnswer = await request(base, `/student/study/questions/${thirdQuestion.result.id}/answer`, {
      method: 'POST', body: { answer: 'true' }
    });
    assert.equal(thirdAnswer.result.correct, false);
    const correctedMistake = await request(base, `/student/study/questions/${firstQuestion.result.id}/answer`, {
      method: 'POST', body: { answer: 'تسجيل العمليات المالية' }
    });
    assert.equal(correctedMistake.result.correct, true);
    const remainingMistakes = await request(base, '/student/study/review');
    assert.equal(remainingMistakes.result.items.length, 1);
    assert.equal(remainingMistakes.result.items[0].question_id, thirdQuestion.result.id);
    const fixedLastMistake = await request(base, `/student/study/questions/${thirdQuestion.result.id}/answer`, {
      method: 'POST', body: { answer: 'false' }
    });
    assert.equal(fixedLastMistake.result.correct, true);
    const noMistakes = await request(base, '/student/study/review');
    assert.equal(noMistakes.result.items.length, 0);

    const result = await request(base, `/student/study/lessons/${lessonId}/finish`, { method: 'POST', body: {} });
    assert.equal(result.response.status, 200, JSON.stringify(result.result));
    assert.equal(result.result.correct, 3);
    assert.equal(result.result.wrong, 0);
    assert.equal(result.result.total, 3);
    assert.equal(result.result.score_percentage, 100);
    assert.equal(result.result.completion_percentage, 100);
    const savedCatalog = await request(base, '/student/study');
    assert.ok(savedCatalog.result.subjects[0].units[0].lessons[0].progress.completed_at);
    const adminCatalog = await request(base, '/interactive-study/manage', { role: 'admin' });
    assert.equal(adminCatalog.result.subjects.length, 2);
    const adminUnit = await request(base, '/interactive-study/manage/units', {
      role: 'admin', method: 'POST', body: { subject_id: 2, title: 'Admin unit' }
    });
    assert.equal(adminUnit.response.status, 201, JSON.stringify(adminUnit.result));
  } finally {
    await new Promise(resolve => server.close(resolve));
    await db.close();
  }
});

test('Interactive Study permissions use the existing role and route permission system', () => {
  assert.deepEqual(routePermission('/api/interactive-study/manage', 'GET'), 'STUDY_VIEW');
  assert.deepEqual(routePermission('/api/interactive-study/manage/units', 'POST'), 'STUDY_CREATE');
  assert.deepEqual(routePermission('/api/interactive-study/manage/lessons/4', 'PATCH'), 'STUDY_EDIT');
  assert.deepEqual(routePermission('/api/interactive-study/manage/lessons/4', 'DELETE'), 'STUDY_DELETE');
  assert.ok(defaultPermissions('doctor').includes('STUDY_CREATE'));
  assert.ok(defaultPermissions('doctor').includes('DOCTOR_STUDENTS_VIEW'));
  assert.ok(!defaultPermissions('doctor').includes('FINANCIAL_REPORTS_VIEW'));
  assert.ok(!defaultPermissions('doctor').includes('ATTENDANCE_VIEW'));
  assert.ok(!defaultPermissions('doctor').includes('STUDENTS_VIEW'));
  assert.deepEqual(routePermission('/api/follow-up', 'GET', {}, 'doctor'), 'DOCTOR_STUDENTS_VIEW');
  assert.deepEqual(routePermission('/api/follow-up', 'GET', {}, 'assistant'), 'FINANCIAL_REPORTS_VIEW');
  assert.ok(defaultPermissions('admin').includes('STUDY_DELETE'));
  assert.deepEqual(defaultPermissions('student').filter(permission => permission.startsWith('STUDY_')), []);
});
